import { hashPassword, verifyPassword } from '@devforge/database';

export async function testAuthSecurity(): Promise<{ name: string; passed: boolean; details: string }> {
  const testName = 'Auth Password Hashing & Verification Security Suite';
  try {
    const rawPass = 'SuperSecretP@ssw0rd!2026';
    const hash = hashPassword(rawPass);

    if (!hash.includes(':')) {
      throw new Error('Hash format must include salt delimiter');
    }

    const [salt, key] = hash.split(':');
    if (!salt || !key || salt.length !== 32 || key.length !== 128) {
      throw new Error('Invalid salt or key length generated by scrypt');
    }

    const isValid = verifyPassword(rawPass, hash);
    if (!isValid) {
      throw new Error('Valid password failed verification against generated hash');
    }

    const isInvalidValid = verifyPassword('WrongPassword123!', hash);
    if (isInvalidValid) {
      throw new Error('Invalid password erroneously passed verification');
    }

    return {
      name: testName,
      passed: true,
      details: 'Password successfully hashed with 16-byte random salt and 64-byte scrypt key. Valid passwords verify; invalid passwords rejected.'
    };
  } catch (err: any) {
    return {
      name: testName,
      passed: false,
      details: `FAILED: ${err.message}`
    };
  }
}
